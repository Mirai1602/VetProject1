-- V5: los textos clínicos (vacunas, desparasitación, parásitos y observaciones) pasan
-- de la tabla "paciente" a la nueva tabla "expediente" (uno por paciente).
-- Se crea la tabla aquí (en vez de dejarla a Hibernate) para poder copiar los datos
-- existentes antes de arrancar. En una base nueva no hace nada: Hibernate la crea.
-- Las columnas viejas de "paciente" se eliminan después en V6.
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM information_schema.tables
               WHERE table_schema = current_schema() AND table_name = 'paciente') THEN

        CREATE TABLE IF NOT EXISTS expediente (
            id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            paciente_id bigint NOT NULL UNIQUE REFERENCES paciente (id),
            historial_vacunas text,
            historial_desparasitacion text,
            control_parasitos text,
            observaciones text
        );

        IF EXISTS (SELECT 1 FROM information_schema.columns
                   WHERE table_schema = current_schema() AND table_name = 'paciente'
                     AND column_name = 'historial_vacunas') THEN
            INSERT INTO expediente (paciente_id, historial_vacunas, historial_desparasitacion,
                                    control_parasitos, observaciones)
            SELECT p.id, p.historial_vacunas, p.historial_desparasitacion,
                   p.control_parasitos, p.observaciones
            FROM paciente p
            WHERE NOT EXISTS (SELECT 1 FROM expediente e WHERE e.paciente_id = p.id);
        ELSE
            INSERT INTO expediente (paciente_id)
            SELECT p.id
            FROM paciente p
            WHERE NOT EXISTS (SELECT 1 FROM expediente e WHERE e.paciente_id = p.id);
        END IF;
    END IF;
END $$;
